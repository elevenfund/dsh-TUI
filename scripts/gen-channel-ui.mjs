#!/usr/bin/env node
/**
 * Single-source codegen for CHANNEL_UI display preferences.
 *
 * Source of truth: the cordis `Config` Schema in `src/dsh-adapter/index.ts`.
 * The script imports the module (via tsx; the entry has no import-time side
 * effects — plugin.ts is loaded lazily) and regenerates the mechanical
 * inventories between `// @gen begin/end` markers:
 *
 *   src/dsh-adapter/channel/state.ts     Pick<ChannelState, ...> channel-UI segment
 *   src/adapter/channel/ui-policy.ts     ChannelPreferences setter list +
 *                                        CHANNEL_UI_PROPERTIES channel-UI segment
 *
 * Adding a display key to the Schema makes it appear in every generated
 * segment on the next run; a key that is NOT a channel-UI preference must be
 * listed in NON_CHANNEL_UI_KEYS below. The exhaustive compile checks around
 * the generated lists are unchanged, so a stale generation still fails tsc.
 *
 * Run: node --import tsx/esm scripts/gen-channel-ui.mjs [--check]
 * Deliberately a standalone command; never wired into rebuild.sh or hot paths.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(scriptDir, '..')
const STATE_PATH = path.join(root, 'src/dsh-adapter/channel/state.ts')
const UI_POLICY_PATH = path.join(root, 'src/adapter/channel/ui-policy.ts')

/** Schema keys that are NOT channel-UI display preferences: session/route
 *  settings, boot-time decisions, module-level stores, and non-channel
 *  settings. A new display key NOT listed here is treated as channel-UI and
 *  flows into every generated segment (compile-checked end to end). */
const NON_CHANNEL_UI_KEYS = new Set([
  'sessionId', 'provider', 'model', 'cwd', 'workspace', 'effort', 'effortDefault',
  'preset', 'modes', 'lang', 'fullscreen', 'terminalImages', 'mermaidDiagrams',
  'shortcuts',
  // Rendering-pipeline switches owned by module stores (applyMathRendering
  // & friends in plugin.ts), not by the channel view.
  'mathRendering', 'mathImageScale', 'mathImageBacking', 'imageBacking', 'latexMath',
  'recapOnOpen',
])

/** Config key -> ChannelState/ChannelUi property name when they differ. */
const PROPERTY_RENAMES = {
  activity: 'activityEnabled',
  contextBar: 'contextBarEnabled',
  // Schema key kept the pre-rename id; state + view store the canonical name.
  minimal: 'minimalUi',
}

/** Config key -> extra live setter names beyond the derived one. The kernel
 * renamed `setMinimal` to `setMinimalUi` and kept the old name as a
 * deprecated alias; both stay in ChannelPreferences. */
const SETTER_ALIASES = {
  minimal: ['setMinimalUi'],
}


/** Config key -> extra property names beyond the derived one. View-layer
 * aliases only: they widen ui-policy's CHANNEL_UI_PROPERTIES, never the
 * ChannelState pick (state stores one canonical field). */
const PROPERTY_ALIASES = {
  minimal: ['minimal'],
}

/** Channel-UI keys without a ChannelPreferences live setter (static config
 *  switch, command-owned preset, or no live toggle). */
const NO_SETTER_KEYS = new Set(['activity', 'activityFrames', 'contextBar'])

const MARKER_BEGIN = (id) => `// @gen begin ${id} — generated by scripts/gen-channel-ui.mjs; do not edit.`
const MARKER_END = '// @gen end'

const checkOnly = process.argv.includes('--check')

/** Hand-maintained surfaces a display key must also reach (semantic work
 *  the generator cannot do): the /settings copy + applyDisplay in
 *  plugin.ts, and the initial values in state.ts. A key missing from a
 *  surface still typechecks — the generator warns instead of silently
 *  skipping it. Presence is textual (schema key OR renamed property). */
const MANUAL_SURFACES = [
  { label: 'applyDisplay + /settings copy', path: path.join(root, 'src/dsh-adapter/plugin.ts') },
  { label: 'initial values', path: STATE_PATH },
]

function auditManualSurfaces(fields) {
  const warnings = []
  for (const surface of MANUAL_SURFACES) {
    let source
    try {
      source = readFileSync(surface.path, 'utf8')
    } catch {
      warnings.push(`gen-channel-ui: WARN cannot audit ${surface.label} (${surface.path} unreadable)`)
      continue
    }
    for (const field of fields) {
      const present = source.includes(`'${field.key}'`) || source.includes(`'${field.property}'`)
        || source.includes(`${field.key}:`) || source.includes(`${field.property}:`)
      if (!present) warnings.push(`gen-channel-ui: WARN "${field.key}" is absent from ${surface.label} — a new display key must reach every hand-maintained surface or that surface silently skips it`)
    }
  }
  for (const warning of warnings) console.warn(warning)
  return warnings.length
}

async function loadChannelUiFields() {
  const schemaUrl = new URL('../src/dsh-adapter/index.ts', import.meta.url)
  const { Config } = await import(schemaUrl.href)
  const dict = Config?.dict
  if (dict === undefined || typeof dict !== 'object') {
    throw new Error('gen-channel-ui: Config schema has no .dict — module import did not yield the cordis Schema')
  }
  const keys = Object.keys(dict)
  for (const key of [...NON_CHANNEL_UI_KEYS, ...Object.keys(PROPERTY_RENAMES), ...NO_SETTER_KEYS]) {
    if (!keys.includes(key)) {
      throw new Error(`gen-channel-ui: policy key "${key}" is absent from the Config schema — update scripts/gen-channel-ui.mjs`)
    }
  }
  return keys.filter(key => !NON_CHANNEL_UI_KEYS.has(key)).map(key => {
    const field = dict[key]
    const meta = field?.meta ?? {}
    const derivedSetter = NO_SETTER_KEYS.has(key) ? undefined : `set${key[0].toUpperCase()}${key.slice(1)}`
    return {
      key,
      property: PROPERTY_RENAMES[key] ?? key,
      properties: [PROPERTY_RENAMES[key] ?? key, ...(PROPERTY_ALIASES[key] ?? [])],
      setter: derivedSetter,
      setters: derivedSetter === undefined ? [] : [derivedSetter, ...(SETTER_ALIASES[key] ?? [])],
      type: field?.type ?? 'unknown',
      hasDefault: meta.default !== undefined,
    }
  })
}

/** Pack items into pipe-separated union lines; fixed wrapping keeps it idempotent. */
function packUnionLines(items, { leadingPipe = false, indent = '  ', maxWidth = 96 } = {}) {
  const lines = []
  let current = ''
  for (const item of items) {
    const piece = `'${item}'`
    const prefix = current === '' ? indent + (leadingPipe ? '| ' : '') : ' | '
    if (current !== '' && current.length + prefix.length + piece.length > maxWidth) {
      lines.push(leadingPipe ? current : `${current} |`)
      current = indent + (leadingPipe ? '| ' : '') + piece
    } else {
      current += prefix + piece
    }
  }
  if (current !== '') lines.push(current)
  return lines
}

function fillBlock(source, id, lines) {
  const beginMarker = MARKER_BEGIN(id)
  const begin = source.indexOf(beginMarker)
  if (begin === -1) throw new Error(`gen-channel-ui: marker "${beginMarker}" not found`)
  const end = source.indexOf(MARKER_END, begin)
  if (end === -1) throw new Error(`gen-channel-ui: missing "${MARKER_END}" for block "${id}"`)
  const before = source.slice(0, begin)
  const indentMatch = /[ \t]*$/.exec(before)
  const indent = indentMatch ? indentMatch[0] : ''
  const after = source.slice(end + MARKER_END.length)
  return before + [beginMarker, ...lines, indent + MARKER_END].join('\n') + after
}

function updateFile(label, filePath, next) {
  const current = readFileSync(filePath, 'utf8')
  if (current === next) {
    console.log(`gen-channel-ui: ${label} unchanged`)
    return false
  }
  if (!checkOnly) writeFileSync(filePath, next)
  console.log(`gen-channel-ui: ${label} ${checkOnly ? 'STALE' : 'updated'}`)
  return true
}

const fields = await loadChannelUiFields()
console.log(`gen-channel-ui: ${fields.length} channel-UI display keys from src/dsh-adapter/index.ts`)
for (const field of fields) {
  console.log(`  ${field.key} (${field.type}, ${field.hasDefault ? 'default set' : 'no default'}${field.setter === undefined ? ', no live setter' : ''})`)
}

const stateSource = readFileSync(STATE_PATH, 'utf8')
const stateUpdated = updateFile('src/dsh-adapter/channel/state.ts', STATE_PATH,
  fillBlock(stateSource, 'channelUiStatePick', packUnionLines(fields.map(field => field.property))))

const setters = fields.flatMap(field => field.setters)
const policySource = readFileSync(UI_POLICY_PATH, 'utf8')
const policyNext = fillBlock(
  fillBlock(policySource, 'channelUiSetters', packUnionLines(setters, { leadingPipe: true })),
  'channelUiProperties', fields.flatMap(field => field.properties.map(property => `  '${property}',`)),
)
const policyUpdated = updateFile('src/adapter/channel/ui-policy.ts', UI_POLICY_PATH, policyNext)

if (checkOnly && (stateUpdated || policyUpdated)) {
  console.error('gen-channel-ui: --check failed — generated blocks are stale; run the generator')
  process.exitCode = 1
}
// Surface audit runs in every mode: the warning is the point (a silently
// skipped hand-maintained surface), not the exit code.
auditManualSurfaces(fields)
